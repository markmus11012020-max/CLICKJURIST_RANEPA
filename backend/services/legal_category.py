# Маркеры авто-шаблонов: теги ``[ORG_1]``, ``[INN_1]``, ``[CASE_1]``
# расставляются именно в B2B-кейсах.
_B2B_PLACEHOLDERS = (
    "[org_",
    "[inn_",
    "[case_",
    "[kpp_",
    "[ogrn_",
)


def _count_matches(text: str, patterns: tuple[str, ...]) -> int:
    """Подсчитать количество вхождений любой из подстрок."""
    if not text:
        return 0
    total = 0
    for p in patterns:
        if not p:
            continue
        total += text.count(p)
    return total


def classify(query: str | None) -> LegalCategory:
    """Определить правовую категорию запроса.

    Возвращает ``"b2b"`` для корпоративных, экономических и договорных споров,
    ``"b2c"`` — для потребительских, бытовых и публично-правовых (ГИБДД и т.п.)
    """
    if not query:
        return "b2c"
    q = query.lower().strip()

    # 1) Плейсхолдеры авто-шаблонов — стопроцентный маркер B2B.
    if _count_matches(q, _B2B_PLACEHOLDERS) > 0:
        return "b2b"

    # 2) Прямые B2B-маркеры.
    b2b_hits = _count_matches(q, _ORG_FORMS) + _count_matches(q, _CORP_TERMS)

    # 3) Прямые B2C-маркеры.
    b2c_hits = _count_matches(q, _CONSUMER_TERMS)

    if b2b_hits == 0 and b2c_hits == 0:
        # 4) Эвристика по умолчанию: бытовая категория (потребитель).
        return "b2c"

    return "b2b" if b2b_hits >= b2c_hits else "b2c"


