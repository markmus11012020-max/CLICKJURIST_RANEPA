LEGAL_DISCLAIMER_DYNAMIC = (
    "\n\n⚠️ Юридическая оговорка: указанные сроки исковой давности исчисляются "
    "не с даты нарушения, а с момента, когда лицо узнало или должно было "
    "узнать о нарушении своих прав (ст. 181 ГК РФ, ст. 196 ГК РФ, ст. 392 ТК РФ). "
    "Точный срок в каждом конкретном случае определяется индивидуально."
)


def with_dynamic_disclaimer(text: str) -> str:
    """Добавить к тексту юридическую оговорку о динамических сроках."""
    if not text:
        return text
    if "Юридическая оговорка" in text:
        return text
    return f"{text.rstrip()}{LEGAL_DISCLAIMER_DYNAMIC}"


